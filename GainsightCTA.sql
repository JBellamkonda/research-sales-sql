SELECT
--  CTA_GSID,
    SFDC_ACCOUNT_ID,
--  EXTERNAL_OBJECT_ID,
--  COMPANY_GSID,
    -- ✅ STRING column → SAFE_CAST + SUBSTR + NULLIF
    SAFE_CAST(SUBSTR(NULLIF(CREATED_DATE, ''), 1, 10) AS DATE)    AS CREATED_DATE,
    SAFE_CAST(SUBSTR(NULLIF(CLOSED_DATE,  ''), 1, 10) AS DATE)    AS CLOSED_DATE,
    IS_CLOSED,
    COMPANY_NAME,
    OWNER_NAME,
    CTA_NAME,
    STATUS_NAME,
    REASON_NAME,
    TYPE_NAME,
    OUTCOME_FACTORS_LABEL,
    LS_TERRITORY_LABEL,
    LS_SEGMENT_LABEL,
    REGION_LABEL,
    TRAINING_TOPIC_LABEL,
    TRAINING_DELIVERY_TYPE_LABEL,
    TOTAL_REGISTRANTS,
    ON_DEMAND_VIEWS,
    TOTAL_ATTENDEES,
    -- ✅ TIMESTAMP column → simple CAST to DATE
    CAST(UPDATED AS DATE)                                          AS UPDATED_DATE,
    AGE,
    POTENTIAL_REVENUE,
    PRODUCT_OPTIONS_LABEL,
    -- ✅ "SOURCE" quoted identifier → SOURCE (no quotes needed in BigQuery)
    SOURCE,
    LOST_OPPTY_REASONS_LABEL,
    PENDING_STATUS_LABEL

FROM `prd-wiley-data.EDW_RESEARCH.GAINSIGHT_CTA`

WHERE
    -- ✅ STRING column → SAFE_CAST + SUBSTR + NULLIF in WHERE clause
    SAFE_CAST(SUBSTR(NULLIF(CREATED_DATE, ''), 1, 10) AS DATE)
        >= DATE_SUB(DATE_TRUNC(DATE_ADD(CURRENT_DATE(), INTERVAL 8 MONTH), YEAR), INTERVAL 2 YEAR)