SELECT
    c.ID,
    c.HIERARCHYNUMBEROFLEADS,
    c.NUMBEROFCONVERTEDLEADS,
    c.HIERARCHYNUMBEROFOPPORTUNITIES,
    c.HIERARCHYNUMBEROFWONOPPORTUNITIES,
    c.AMOUNTALLOPPORTUNITIES,
    c.AMOUNTWONOPPORTUNITIES,
    c.EXPECTEDREVENUE,
    c.HIERARCHYBUDGETEDCOST,
    c.HIERARCHYACTUALCOST,
    c.NAME,
    c.REGION__C,
    c.NUMBER_OF_MQLS__C,
    c.NUMBER_OF_SQLS__C,
--  u.NAME AS OwnerName,
    c.PARENTID,
    pc.NAME                             AS Parent_Campaign_Name,
    c.ULTIMATE_PARENT_ID_STRING__C,
    upc.NAME                            AS Ultimate_Parent_Name
--  u1.NAME AS LEADORCONTACTOWNERName,
--  EXTRACT(YEAR FROM DATE_ADD(CAST(cm.CAMPAIGN_MEMBER_ASSIGNED_DATE__C AS DATE), INTERVAL 8 MONTH)) AS FY_CM_Assigned_Date

FROM `prd-wiley-data.ODS_SFDC.T_S_SFDC_CAMPAIGN` c

LEFT JOIN `prd-wiley-data.ODS_SFDC.T_S_SFDC_CAMPAIGN` pc
    ON pc.ID = c.PARENTID

LEFT JOIN `prd-wiley-data.ODS_SFDC.T_S_SFDC_CAMPAIGN` upc
    ON upc.ID = c.ULTIMATE_PARENT_ID_STRING__C

WHERE
    -- ✅ FIX: TIMESTAMP column — CAST to DATE for comparison with date literal
    CAST(c.CREATEDDATE AS DATE) >= DATE '2023-05-01'
--  AND c.ID = '701WQ000003kfRWYAY'